<?php
/**
 * Тесты нормализации телефона (bv_normalize_phone из lib.php).
 * Запуск: php server/tests/phone.test.php — код выхода 0, если всё прошло.
 */

declare(strict_types=1);

require dirname(__DIR__) . '/lib.php';

$cases = [
    // вход → ожидание
    ['+7 912 345-67-89',        '+79123456789'],
    ['+7 (912) 345-67-89',      '+79123456789'],
    ['79123456789',             '+79123456789'],
    ['89123456789',             '+79123456789'],
    ['8 (912) 345 67 89',       '+79123456789'],
    ['9123456789',              '+79123456789'],
    ['912-345-67-89',           '+79123456789'],
    ['  +7 912 345 67 89  ',    '+79123456789'],
    ['tel:+79123456789',        '+79123456789'],
    ['7 912 345 67 89 доб.',    '+79123456789'],
    [79123456789,               '+79123456789'],   // число, не строка
    ['8123456789',              '+78123456789'],   // 10 цифр с 8 в начале — добавляем +7 как есть
    ['+7 912 345-67-8',         null],             // 10 цифр с кодом — всего 10? нет: 7+9 = 10 цифр → +7… см. ниже
    ['12345',                   null],
    ['',                        null],
    ['абв',                     null],
    ['+1 650 555 0100',         null],             // 11 цифр, но не 7/8
    ['+7 912 345-67-890',       null],             // 12 цифр
    ['999999999',               null],             // 9 цифр
    [null,                      null],
    [['+79123456789'],          null],             // массив
    [true,                      null],
];

// Особый случай из таблицы: «+7 912 345-67-8» — это 10 цифр (7 + девять),
// по правилу «десять цифр — добавляем +7» получится +77912345678. Это
// ожидаемое поведение правила, фиксируем его явно.
$cases[12] = ['+7 912 345-67-8', '+77912345678'];

$failed = 0;
foreach ($cases as $i => [$input, $expected]) {
    $actual = bv_normalize_phone($input);
    $ok = $actual === $expected;
    if (!$ok) {
        $failed++;
    }
    printf("%s %2d %-28s → %s\n", $ok ? 'ok  ' : 'FAIL', $i, json_encode($input, JSON_UNESCAPED_UNICODE), var_export($actual, true));
}
echo $failed === 0 ? "\nВсе " . count($cases) . " случаев прошли\n" : "\nПровалено: $failed\n";
exit($failed === 0 ? 0 : 1);
